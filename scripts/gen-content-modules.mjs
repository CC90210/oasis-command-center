#!/usr/bin/env node
/**
 * scripts/gen-content-modules.mjs - bundle the Playbook markdown and the AI
 * prompt text into TypeScript modules, so the Worker never reads a file.
 *
 * WHY. Production is an OpenNext Cloudflare Worker. workerd has no filesystem:
 * a readFile of content/playbooks/*.md passes every local test and every
 * `next dev`, then fails on the live Worker. lib/playbooks.ts caught that
 * failure and answered [] / null, so /playbook/10-oasis-loop showed "Page not
 * found" and the Operating manual section vanished (audit 2026-09-30,
 * playbook-fs-reads-on-workers). lib/prompts/index.ts read its .txt prompts the
 * same way at module init. Being copied into .open-next/ by the file tracer
 * does not make a file readable: wrangler uploads the bundled JS only.
 *
 * WHAT IT WRITES (both committed, both regenerated by `npm run build` through
 * the `prebuild` script):
 *   lib/playbooks.generated.ts   from content/playbooks/*.md (INDEX.md skipped)
 *   lib/prompts/generated.ts     from lib/prompts/*.txt
 *
 * DETERMINISTIC. Files are read in sorted order, CRLF is normalised to LF (a
 * Windows checkout with core.autocrlf must produce the same module as Linux
 * CI), and every character outside printable ASCII is written as a \uXXXX
 * escape, so the generated source is pure ASCII: nothing in it can push the
 * Worker bundle out of V8's one-byte source form (tests/worker-source-one-byte).
 *
 * tests/playbook-docs.test.ts regenerates both modules in memory and fails when
 * a committed module differs from its sources, so editing a .md without
 * running this script fails CI instead of shipping a stale page.
 *
 * Usage:
 *   node scripts/gen-content-modules.mjs          write both modules
 *   node scripts/gen-content-modules.mjs --check  exit 1 if either is stale
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DEFAULT_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const PLAYBOOKS_MODULE = "lib/playbooks.generated.ts";
export const PROMPTS_MODULE = "lib/prompts/generated.ts";

const HEADER =
  "// GENERATED by scripts/gen-content-modules.mjs. Do not edit by hand:\n" +
  "// edit the source file and run `node scripts/gen-content-modules.mjs`.\n" +
  "// tests/playbook-docs.test.ts fails when this module differs from its sources.\n";

/** A TypeScript string literal holding `text`, ASCII only. */
export function tsString(text) {
  return JSON.stringify(text).replace(/[\u007f-\uffff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}

function readNormalised(path) {
  return readFileSync(path, "utf8").replace(/^\ufeff/, "").replace(/\r\n?/g, "\n");
}

export function renderPlaybooksModule(root = DEFAULT_ROOT) {
  const dir = join(root, "content", "playbooks");
  const files = existsSync(dir)
    ? readdirSync(dir).filter((n) => n.endsWith(".md") && n !== "INDEX.md").sort()
    : [];
  const rows = files.map((file) => `  { file: ${tsString(file)}, raw: ${tsString(readNormalised(join(dir, file)))} },`);
  return (
    HEADER +
    "// Sources: content/playbooks/*.md (INDEX.md excluded).\n\n" +
    "export type BundledPlaybookSource = { readonly file: string; readonly raw: string };\n\n" +
    "export const PLAYBOOK_SOURCES: readonly BundledPlaybookSource[] = [\n" +
    rows.join("\n") +
    (rows.length ? "\n" : "") +
    "];\n"
  );
}

export function renderPromptsModule(root = DEFAULT_ROOT) {
  const dir = join(root, "lib", "prompts");
  const files = readdirSync(dir).filter((n) => n.endsWith(".txt")).sort();
  const rows = files.map((file) => `  ${tsString(file)}: ${tsString(readNormalised(join(dir, file)))},`);
  return (
    HEADER +
    "// Sources: lib/prompts/*.txt.\n\n" +
    "export const PROMPT_SOURCES: Readonly<Record<string, string>> = {\n" +
    rows.join("\n") +
    (rows.length ? "\n" : "") +
    "};\n"
  );
}

/** Each module as it should be on disk, keyed by its repo-relative path. */
export function renderAll(root = DEFAULT_ROOT) {
  return {
    [PLAYBOOKS_MODULE]: renderPlaybooksModule(root),
    [PROMPTS_MODULE]: renderPromptsModule(root),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [rel, content] of Object.entries(renderAll())) {
    const path = join(DEFAULT_ROOT, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8").replace(/\r\n?/g, "\n") : null;
    if (current === content) continue;
    if (check) {
      stale.push(rel);
      continue;
    }
    writeFileSync(path, content, "utf8");
    console.log(`gen-content-modules: wrote ${rel}`);
  }
  if (check && stale.length) {
    console.error(`gen-content-modules: stale ${stale.join(", ")}. Run node scripts/gen-content-modules.mjs`);
    process.exit(1);
  }
  if (!check) console.log("gen-content-modules: content modules are current");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
