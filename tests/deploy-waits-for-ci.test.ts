/**
 * Production deploys only what CI passed.
 *
 * WHY (2026-10-19 audit). deploy-cloudflare.yml deployed every push to main,
 * untested, and main has no branch protection: a merge whose typecheck, tests
 * or build were red went live with nothing in the way. That same day a red CI
 * on #709 (a pinned-SQL test) would have shipped had it merged before the fix.
 * The deploy now starts when the CI workflow completes on a push to main,
 * deploys only on success, and checks out exactly the commit CI tested.
 *
 * Two halves hold this together, so both are pinned here:
 *  - the deploy waits for CI's success (deploy-cloudflare.yml, GENERATED by
 *    Business-Empire-Agent wrangler_tool.py `workflow`; regenerate, don't
 *    hand-edit);
 *  - CI cancels its older run on main when a newer push lands (ci.yml
 *    concurrency), so a superseded commit ends "cancelled", is never deployed,
 *    and two successes cannot deploy out of order.
 *
 * Text checks, not a YAML parse: the repo has no direct YAML dependency.
 *
 * Run: node --conditions=react-server --import tsx tests/deploy-waits-for-ci.test.ts
 */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const root = join(__dirname, "..");
const deploy = readFileSync(join(root, ".github/workflows/deploy-cloudflare.yml"), "utf8").replace(/\r\n/g, "\n");
const ci = readFileSync(join(root, ".github/workflows/ci.yml"), "utf8").replace(/\r\n/g, "\n");

const onBlock = deploy.slice(deploy.indexOf("\non:\n"), deploy.indexOf("\nconcurrency:"));

// The deploy waits for CI, and a push alone never deploys.
assert.ok(onBlock.includes('  workflow_run:\n    workflows: ["CI"]\n    types: [completed]\n    branches: [main]\n'),
  "the deploy runs when the CI workflow completes on main");
assert.ok(!/^\s{2}push:/m.test(onBlock), "a push to main must not start a deploy by itself");
assert.ok(/^\s{2}workflow_dispatch:/m.test(onBlock), "a deliberate manual deploy stays possible");

// Only a successful CI run of a push deploys, and it deploys that run's commit.
const jobIf = deploy.slice(deploy.indexOf("  deploy:\n"), deploy.indexOf("    runs-on:"));
const cond = jobIf.replace(/\s+/g, " ");
assert.ok(cond.includes("github.event.workflow_run.conclusion == 'success'"), "a failed or cancelled CI run does not deploy");
assert.ok(cond.includes("github.event.workflow_run.event == 'push'"), "a pull request's CI run does not deploy");
assert.ok(cond.includes("github.event_name == 'workflow_dispatch'"), "a manual run still deploys");
assert.ok(deploy.includes("ref: ${{ github.event.workflow_run.head_sha || github.sha }}"),
  "the deploy checks out the commit CI tested, not whatever main points at now");
assert.ok(deploy.includes("DEPLOY_GIT_SHA:${{ github.event.workflow_run.head_sha || github.sha }}"),
  "/api/health reports the commit actually deployed");

// CI's half: one run per ref on main, the older one cancelled.
assert.ok(/on:\n(?:.*\n)*?\s{2}push:\n\s{4}branches: \[main\]/.test(ci), "CI runs on every push to main");
assert.ok(/concurrency:\n\s{2}group: ci-\$\{\{ github\.ref \}\}\n\s{2}cancel-in-progress: true/.test(ci),
  "CI cancels a superseded run on main, so it can never be deployed out of order");
assert.ok(/^name: CI$/m.test(ci), "the deploy waits for the workflow named CI");

console.log("deploy-waits-for-ci: all assertions passed");
